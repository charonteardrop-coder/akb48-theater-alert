  const h = buildHistory([
    { pub: '2013-03-20T12:00:00+09:00', url: 'a', shows: [{ date: '2013-03-28', time: '19:00', title: '「大島チームK」公演', note: '', members: ['板野友美', '宮澤佐江'], url: '' }], changes: [] },
    { pub: '2013-03-27T22:00:00+09:00', url: 'b', shows: [], changes: [{ date: '2013-03-28', time: '19:00', out: ['板野友美'], in: ['佐藤亜美菜'] }] },
  ]);
  assert.deepEqual(h.shows[0].members, ['宮澤佐江', '佐藤亜美菜']);
